# ------------------------------------------------------------------ raw zone
def download_missing() -> list[str]:
    fetched = []
    RAW.mkdir(parents=True, exist_ok=True)
    for stem in APPROVED:
        dest = RAW / f"{stem}.xpt"
        if dest.exists():
            continue
        url = URL.format(year=YEAR[stem[-1]], stem=stem)
        tmp = dest.with_suffix(".part")
        urllib.request.urlretrieve(url, tmp)
        tmp.replace(dest)
        fetched.append(stem)
    return fetched


def manifest() -> str:
    entries = []
    for stem in APPROVED:
        p = RAW / f"{stem}.xpt"
        entries.append({"path": p.name, "url": URL.format(year=YEAR[stem[-1]], stem=stem),
                        "bytes": p.stat().st_size, "sha256": sha256_file(p)})
    if MANIFEST.exists():
        old = {e["path"]: e["sha256"] for e in json.loads(MANIFEST.read_text())["files"]}
        bad = [e["path"] for e in entries if old.get(e["path"]) != e["sha256"]]
        if bad:
            raise SystemExit(f"raw files differ from {MANIFEST.name}: {bad}. The release "
                             "changed or a file is corrupt; inspect before rebuilding.")
        return "verified against existing manifest"
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps({
        "dataset": "nhanes",
        "official_landing_page": "https://wwwn.cdc.gov/nchs/nhanes/",
        "cycles": {"G": "2011-2012", "H": "2013-2014"},
        "access_mode": "public_download",
        "access_date_utc": dt.datetime.now(dt.UTC).isoformat(timespec="seconds"),
        "scope": "eight public-use files: DEMO, DPQ, PAXHD, PAXDAY for cycles G and H",
        "license_text_verbatim": "NHANES public-use files; see the NCHS data use agreement",
        "license_verified_by_human": False,
        "n_files": len(entries),
        "files": entries,
        "not_downloaded": PAXMIN,
    }, indent=2), encoding="utf-8")
    return "written"


# ------------------------------------------------------------ reconciliation
def _counts(s: pd.Series) -> dict[str, int]:
    out = {str(int(k)): int(v) for k, v in s.dropna().value_counts().items()}
    out["missing"] = int(s.isna().sum())
    return out


def reconcile(frames: dict[str, pd.DataFrame]) -> pd.DataFrame:
    rows = []
    for comp in nhanes.COMPONENTS:
        for cyc in nhanes.CYCLES:
            stem = f"{comp}_{cyc}"
            df = frames[comp][frames[comp]["cycle"] == cyc]
            rows.append({"file": stem, "variable": "(rows)", "code": "",
                         "codebook_count": CODEBOOK_ROWS[stem], "file_count": len(df)})
            for var, table in CODEBOOK[stem].items():
                got = _counts(df[var])
                for code, n in table.items():
                    rows.append({"file": stem, "variable": var, "code": code,
                                 "codebook_count": n, "file_count": got.get(code, 0)})
    out = pd.DataFrame(rows)
    out["match"] = out["codebook_count"] == out["file_count"]
    return out


def cross_file_checks(frames: dict[str, pd.DataFrame]) -> dict:
    demo, dpq, hd, day = (frames[c] for c in nhanes.COMPONENTS)
    mec18 = demo[(demo.RIDSTATR == 2) & (demo.RIDAGEYR >= nhanes.MIN_AGE)]
    items = dpq[list(nhanes.PHQ9_ITEMS)]
    out = {}
    for cyc in nhanes.CYCLES:
        d = dpq[dpq.cycle == cyc]
        it = items[dpq.cycle == cyc]
        out[cyc] = {
            "dpq_rows": int(len(d)),
            "demo_mec_examined_age18plus": int((mec18.cycle == cyc).sum()),
            "dpq_seqn_subset_of_mec_age18plus": bool(
                d.SEQN.isin(mec18[mec18.cycle == cyc].SEQN).all()),
            "dpq_any_item_missing": int(it.isna().any(axis=1).sum()),
            "dpq_max_single_item_missing": int(it.isna().sum().max()),
            "dpq_all_items_missing": int(it.isna().all(axis=1).sum()),
            "dpq_any_item_7_or_9": int(it.isin(nhanes.PHQ9_INVALID_CODES).any(axis=1).sum()),
            "paxhd_status1": int(((hd.cycle == cyc) & (hd.PAXSTS == 1)).sum()),
            "paxday_unique_seqn": int(day[day.cycle == cyc].SEQN.nunique()),
            "paxday_seqn_equals_status1": bool(
                set(day[day.cycle == cyc].SEQN)
                == set(hd[(hd.cycle == cyc) & (hd.PAXSTS == 1)].SEQN)),
        }
    return out


# --------------------------------------------------------------------- checks
def leakage(features: pd.DataFrame, cols: list[str]) -> dict:
    scan = leakage_scan(features, cols)
    dpq_like = [c for c in cols if re.search(r"dpq|phq|label", c, flags=re.I)]
    return {
        "leakage_scan": scan,
        "label_in_feature_columns": "label" in cols,
        "dpq_or_phq_named_columns": dpq_like,
        "all_columns_from_paxday_definitions": set(cols) == set(nhanes.FEATURE_COLUMNS),
        "feature_sources": ("every feature is computed in readers/nhanes.py from PAXDAY "
                            "day-summary variables and the count of valid PAXDAY days; the "
                            "DPQ frame is used only by nhanes.phq9() to form `label`"),
        "status": ("PASS" if scan["status"] == "PASS" and "label" not in cols
                   and not dpq_like and set(cols) == set(nhanes.FEATURE_COLUMNS)
                   else "FAIL"),
    }


def partial_day_evidence(frames: dict[str, pd.DataFrame]) -> dict:
    """PAXTMD of the dropped partial days vs the kept days, over all PAXDAY rows."""
    day = frames["PAXDAY"]
    part = nhanes.partial_day_mask(day)
    last = day.groupby("SEQN")["PAXDAYD"].transform("max")
    return {
        "rule": "drop PAXDAYD == 1 and each person's final PAXDAYD before the valid-day rule",
        "paxday_rows": int(len(day)),
        "rows_dropped": int(part.sum()),
        "dropped_share_paxtmd_below_1440": round(float((day.loc[part, "PAXTMD"] < 1440).mean()), 6),
        "kept_share_paxtmd_equal_1440": round(float((day.loc[~part, "PAXTMD"] == 1440).mean()), 6),
        "participants_final_day_below_9": int((last.groupby(day["SEQN"]).first() < 9).sum()),
        "days_contiguous_from_1": bool((day.groupby("SEQN")["PAXDAYD"].agg(
            lambda x: sorted(x) == list(range(1, len(x) + 1)))).all()),
    }


def update_checks(**fields) -> dict:
    cur = json.loads(CHECKS.read_text()) if CHECKS.exists() else {}
    cur.update(fields)
    CHECKS.parent.mkdir(parents=True, exist_ok=True)
    CHECKS.write_text(json.dumps(cur, indent=2))
    return cur


def run_pytest() -> dict:
    # pyproject already adds -q; a second -q would suppress the summary line.
    r = subprocess.run([sys.executable, "-m", "pytest", "tests/unit/test_nhanes_reader.py",
                        "-p", "no:cacheprovider"], cwd=ROOT, capture_output=True, text=True)
    tail = r.stdout.strip().splitlines()[-1] if r.stdout.strip() else ""
    grab = lambda k: int(m.group(1)) if (m := re.search(rf"(\d+) {k}", tail)) else 0
    print(tail)
    return {"tests_passed": grab("passed"), "tests_failed": grab("failed") + grab("error")}


def run_smoke(permutations: int) -> bool:
    out = WS / "results" / "participant_level_smoke.json"
    r = subprocess.run([sys.executable, "scripts/participant_level_eval.py", "--workspace",
                        str(WS), "--permutations", str(permutations), "--tag", "smoke",
                        "--out", str(out)], cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr[-3000:])
        return False
    rep = json.loads(out.read_text())
    ok = (rep["permutation_test"].get("B_effective") == permutations
          and rep["n_participants"] == json.loads(CHECKS.read_text())["n_participants"])
    print(json.dumps({"auroc": rep["participant_metrics"].get("auroc"),
                      "p": rep["permutation_test"].get("p_value_plus_one"),
                      "B": rep["permutation_test"].get("B_effective")}))
    return bool(ok)


# ----------------------------------------------------------------------- main
def main() -> int:
    global CHECKS
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true",
                    help="fetch any of the eight public-use files that are missing")
    ap.add_argument("--pytest", action="store_true",
                    help="run tests/unit/test_nhanes_reader.py and record counts")
    ap.add_argument("--smoke", type=int, default=0, metavar="B",
                    help="run participant_level_eval.py with B permutations (tag smoke)")
    ap.add_argument("--checks-out", default=str(CHECKS),
                    help="checks JSON to update (default reports/bigdata/nhanes_build_checks.json)")
    a = ap.parse_args()
    CHECKS = Path(a.checks_out)

    fetched = download_missing() if a.download else []
    man = manifest()
    frames = nhanes.load_frames(RAW)

    rec = reconcile(frames)
    for sub in ("interim", "validation", "results"):
        (WS / sub).mkdir(parents=True, exist_ok=True)
    rec.to_csv(WS / "validation" / "codebook_reconciliation.csv", index=False)
    if not rec["match"].all():
        print(rec[~rec["match"]].to_string())
        raise SystemExit("file counts differ from the CDC codebook; not building")
    cross = cross_file_checks(frames)
    partial_days = partial_day_evidence(frames)

    cohort = nhanes.build_cohort(frames)
    features, cols = nhanes.build_features(cohort.panel)
    leak = leakage(features, cols)
    (WS / "validation" / "leakage_check.json").write_text(json.dumps(leak, indent=2))
    if leak["status"] != "PASS":
        raise SystemExit(f"leakage check failed: {json.dumps(leak)[:2000]}")

    features.to_csv(WS / "interim" / "features.csv", index=False)
    (WS / "interim" / "feature_columns.json").write_text(json.dumps(cols, indent=2))
    cohort.metadata.to_csv(WS / "validation" / "participant_metadata.csv", index=False)
    cohort.flow.to_csv(WS / "validation" / "cohort_flow.csv", index=False)
    strata = (cohort.metadata.groupby(["cycle", "sdmvstra"])
              .agg(n=("label", "size"), n_positive=("label", "sum"),
                   n_psu=("sdmvpsu", "nunique")).reset_index())
    strata.to_csv(WS / "validation" / "strata_summary.csv", index=False)

    per_person = cohort.panel.groupby("study_id").size()
    summary = {
        "n_participants": int(cohort.metadata.shape[0]),
        "n_positive": int(cohort.metadata["label"].sum()),
        "n_windows": int(len(features)),
        "median_days": float(per_person.median()),
        "n_strata": int(cohort.metadata["sdmvstra"].nunique()),
    }
    report = {
        **summary,
        "prevalence": round(summary["n_positive"] / summary["n_participants"], 4),
        "n_feature_columns": len(cols),
        "days_per_participant": {"min": int(per_person.min()), "max": int(per_person.max())},
        "rules": {"min_age": nhanes.MIN_AGE, "phq9_cutoff": nhanes.PHQ9_CUTOFF,
                  "phq9_exclude_codes": list(nhanes.PHQ9_INVALID_CODES) + ["missing"],
                  "min_wake_wear_minutes": nhanes.MIN_WAKE_WEAR_MINUTES,
                  "min_valid_days": nhanes.MIN_VALID_DAYS},
        "estimand": "association; relative features use all valid days",
        "salt_source": SALT_SOURCE,
        "manifest": man,
        "downloaded_this_run": fetched,
        "codebook_rows_checked": int(len(rec)),
        "codebook_mismatches": int((~rec["match"]).sum()),
        "cross_file": cross,
        "partial_day_rule": partial_days,
        "paxhand": {"rule": "PAXHAND = 9 (wrist unknown) is kept", **cohort.notes},
        "stage2_minute_files": {"status": "not downloaded; not used",
                                "files": PAXMIN},
    }
    (WS / "validation" / "build_report.json").write_text(json.dumps(report, indent=2))
    update_checks(**summary, stage2_minute_features=False)
    print(json.dumps({k: report[k] for k in (*summary, "prevalence", "salt_source",
                                               "manifest", "codebook_mismatches")}, indent=2))
    print(cohort.flow.to_string(index=False))

    if a.pytest:
        update_checks(**run_pytest())
    if a.smoke:
        update_checks(smoke_perm_ok=run_smoke(a.smoke))
    cur = json.loads(CHECKS.read_text())
    cur.setdefault("smoke_perm_ok", False)
    cur.setdefault("tests_passed", 0)
    cur.setdefault("tests_failed", 0)
    CHECKS.write_text(json.dumps(cur, indent=2))
    return 0


if __name__ == "__main__":
    np.seterr(all="ignore")
    raise SystemExit(main())
