def ensure_salt() -> str:
    env = os.environ.get("WEARABLEDATA_ID_SALT")
    if env:
        if env in PUBLIC_SALTS:
            raise SystemExit("WEARABLEDATA_ID_SALT is a public smoke/test salt; refusing "
                             "to build real-data study IDs with it")
        return "environment variable"
    if SALT_FILE.exists():
        os.environ["WEARABLEDATA_ID_SALT"] = SALT_FILE.read_text(encoding="utf-8").strip()
        return "data/raw/nhanes/.salt (existing)"
    RAW.mkdir(parents=True, exist_ok=True)
    salt = secrets.token_hex(32)
    SALT_FILE.write_text(salt, encoding="utf-8")
    os.chmod(SALT_FILE, 0o600)
    os.environ["WEARABLEDATA_ID_SALT"] = salt
    return "data/raw/nhanes/.salt (generated by this run)"


