"""Build the NHANES 2011-2014 workspace `reports/real_nhanes/`.

Only the eight small public-use files are used (DEMO, DPQ, PAXHD, PAXDAY for
cycles G and H). The minute-level files PAXMIN_G/H are not needed and are not
read.

Outputs, following the workspace contract the analysis scripts read:

    reports/real_nhanes/interim/features.csv            study_id, cutoff_day, label, features
    reports/real_nhanes/interim/feature_columns.json
    reports/real_nhanes/validation/participant_metadata.csv   SDMVSTRA, SDMVPSU, age, sex, cycle
    reports/real_nhanes/validation/cohort_flow.csv       counts at every exclusion step
    reports/real_nhanes/validation/codebook_reconciliation.csv
    reports/real_nhanes/validation/strata_summary.csv
    reports/real_nhanes/validation/leakage_check.json
    reports/real_nhanes/validation/build_report.json
    data/manifests/nhanes.json                           sha256 of each raw file
    reports/bigdata/nhanes_build_checks.json   (or the path given by --checks-out)

The partial first and final PAXDAY days are dropped before the
valid-day rule (cohort flow steps 8 and 12), and PAXHAND = 9 (wrist unknown)
participants are kept and counted (build_report.json, "paxhand").

Study IDs are salted (WEARABLEDATA_ID_SALT). If the variable is unset, the salt is
read from data/raw/nhanes/.salt, or generated there on first use. That file is in
the git-ignored raw zone. `_bootstrap` would otherwise install a public smoke salt,
so the salt is resolved before it is imported.
"""
